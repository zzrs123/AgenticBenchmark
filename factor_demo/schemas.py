"""Typed data structures for the 3-Agent Counterfactual Meta-Benchmark Demo.

Separates:
1. Label-free observable dataset descriptors (`d_obs`) vs. reference-dependent diagnostics (`d_ref`).
2. Auditable method descriptors (`m_core`, `c_aux`) grounded in exact source-code line spans.
3. Pre-registered operational intervention hypotheses and 2x3 factorial experimental records.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
from typing import Any, Dict, List, Optional


@dataclass
class CodeSpan:
    """Exact source code provenance for an extracted method property."""

    file_path: str
    start_line: int
    end_line: int
    symbol: str
    snippet: str


@dataclass
class DatasetProfile:
    """Structured output of Agent 1 (Dataset-Character Agent)."""

    dataset_id: str
    split: str  # "exploration" or "confirmation"
    platform_tag: str
    tissue_tag: str
    n_units: int
    n_genes: int
    n_domains: int
    # Label-free observable features (usable for out-of-sample recommendation)
    d_obs: Dict[str, float]
    # Reference-dependent diagnostic features (only for retrospective analysis)
    d_ref: Dict[str, float]
    agent_summary: str = ""
    tool_trace: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class MethodProfile:
    """Structured output of Agent 2 (Method-Character Agent)."""

    method_id: str
    display_name: str
    family: str
    source_file: str
    # Target architectural / inductive-bias descriptors
    m_core: Dict[str, float]
    # Coupled auxiliary pipeline descriptors (preprocessing, clustering head, scaling)
    c_aux: Dict[str, float]
    # Verifiable code spans for every extracted attribute
    evidence_spans: Dict[str, CodeSpan]
    supported_hooks: List[str]
    agent_summary: str = ""
    tool_trace: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class ScreeningCandidate:
    """Candidate interaction surfaced by the outer-loop mixed-effects model."""

    rank: int
    d_feature: str
    m_or_c_feature: str
    feature_group: str  # "D_x_M" or "D_x_C"
    estimate_w: float
    stability_prob: float
    priority_score: float
    direction_hint: str


@dataclass
class PreRegisteredHypothesis:
    """Locked operational experiment specification generated by Agent 3 before running interventions."""

    hypothesis_id: str
    title: str
    rationale_from_screening: str
    target_task: str
    data_operator_name: str
    data_operator_doses: List[float]
    label_evolution_rule: str
    target_methods: List[str]
    method_arms: List[str]  # ["orig", "refac", "self", "null"]
    competing_pipeline_factor: Optional[str]
    tuning_protocols: List[str]  # ["fixed", "retuned"]
    primary_metric: str
    equivalence_margin: float
    expected_direction: str
    falsification_rule: str

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class ValidityAuditRecord:
    """Intervention validity, off-target drift, and code-equivalence diagnostics."""

    slice_id: str
    operator_name: str
    dose: float
    target_shift_z: float
    max_off_target_drift_z: float
    off_target_details: Dict[str, float]
    gene_corr_frobenius_drift: float
    code_equiv_max_diff: Dict[str, float]
    convergence_ok_rate: float
    passed_validity_check: bool
    notes: str = ""

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class FactorialContrastResult:
    """2x3 factorial summary and confirmatory inference across held-out slices."""

    hypothesis_id: str
    method_id: str
    tuning_protocol: str
    operator_name: str
    dose_low: float
    dose_high: float
    metric_name: str
    # Mean performance in each (dose, arm) cell across confirmation slices
    cell_means: Dict[str, float]
    # Simple effects at low and high doses
    simple_agg_low: float     # refac - self at dose_low
    simple_agg_high: float    # refac - self at dose_high
    simple_topo_low: float    # refac - null at dose_low
    simple_topo_high: float   # refac - null at dose_high
    # 2x2 Factorial Interaction Contrasts
    tau_int_agg_mean: float
    tau_int_topo_mean: float
    tau_int_topo_ci_low: float
    tau_int_topo_ci_high: float
    p_value_two_sided: float
    equivalence_margin: float
    evidence_state: str  # "Supported Interaction" | "Practically Equivalent" | "Inconclusive" | "Protocol-Sensitive"
    slice_level_taus: List[float] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)
